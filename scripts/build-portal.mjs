// Bundles the portal frontend into src/portal/assets.gen.js and writes the D1 migration.
// Run automatically by `npm run deploy` (predeploy) and `npm test` (pretest).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { SCHEMA, MIGRATION_V2, MIGRATION_V3 } from "../src/portal/schema.js";

const root = new URL("../", import.meta.url);
const js = readFileSync(new URL("src/portal/web/app.js", root), "utf8");
const css = readFileSync(new URL("src/portal/web/app.css", root), "utf8");
const hash = createHash("sha256").update(js).update(css).digest("hex").slice(0, 12);
writeFileSync(
  new URL("src/portal/assets.gen.js", root),
  `// AUTO-GENERATED by scripts/build-portal.mjs — do not edit. Sources: src/portal/web/\n` +
    `export const ASSET_HASH = ${JSON.stringify(hash)};\n` +
    `export const APP_JS = ${JSON.stringify(js)};\n` +
    `export const APP_CSS = ${JSON.stringify(css)};\n`,
);
writeFileSync(
  new URL("migrations/0001_portal.sql", root),
  "-- QVK Beta Portal: additive schema (portal_* tables only). Safe to re-run.\n" + SCHEMA.map((s) => s + ";").join("\n") + "\n",
);
writeFileSync(
  new URL("migrations/0002_portal_nick_auth.sql", root),
  "-- QVK Beta Portal v2: nickname + password accounts, optional Telegram link.\n" + MIGRATION_V2.map((s) => s + ";").join("\n") + "\n",
);
writeFileSync(
  new URL("migrations/0003_portal_news_push.sql", root),
  "-- QVK Beta Portal v3: news broadcast (Telegram + Web Push). The Worker also applies it on first request.\n" + MIGRATION_V3.map((s) => s + ";").join("\n") + "\n",
);
console.log("portal assets built", hash);
